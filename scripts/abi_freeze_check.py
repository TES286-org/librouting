#!/usr/bin/env python3
"""ABI freeze check: compare the C ABI + C++ wrapper surface at two
git revisions.

The `abi-freeze` job in `.github/workflows/ci.yml` guards the C ABI
between the baseline tag and `HEAD`: the headers (`include/lr_ffi.h`
+ `include/librouting.hpp`) may only grow additively. A removed or
modified symbol is a breaking change.

The original check did this with a one-liner:

    git diff <baseline>..HEAD -- include/lr_ffi.h include/librouting.hpp \
        | grep '^-' | grep -v '^---'

That grep-based check is too coarse: it flags every removed line in
the diff, including comment text, blank lines, and the inside of
multi-line declarations cbindgen reformatted between versions. A
comment reflow or a function declaration wrapped across lines (the
signature itself unchanged) lights up the check even though no
symbol changed. Since the v1.0.0 cut, cbindgen has reformatted the
header several times — every reformat broke the gate even when the
ABI itself was additive.

This script is the precise replacement. For each header it:

1. Strips comments (block `/* ... */` and line `// ...`) — comment
   text is not part of the ABI contract.
2. Joins continuation lines so a multi-line declaration (cbindgen
   wraps long signatures at 80 columns) becomes a single logical
   block. Logical blocks are brace-balanced: a `;` inside a struct
   body does not end the block, and a C++ inline-function body
   (`{ ... }` with no trailing `;`) ends the block at the closing
   brace.
3. Normalises whitespace runs to a single space and trims leading /
   trailing space.
4. Extracts the four kinds of ABI surface:
   - `#define NAME VALUE` — preprocessor constants embedders compile
     against (e.g. `LR_ERR_NULL (-1)`).
   - `typedef ... NAME;` — type aliases (including `typedef struct
     Foo { ... } *handle_t;` aliased pointer types).
   - `struct NAME { ... };`, `enum NAME { ... };`,
     `union NAME { ... };` and `class NAME { ... };` — the field /
     method layout embedders rely on for `sizeof`, offsets and the
     public method surface.
   - function declarations — anything that ends with `;`, contains
     a `(`, and is not a typedef / struct / enum / class. For the
     C++ header, `inline RET name(params) { ... }` definitions are
     captured as `RET name(params)` (the body is implementation
     detail — embedders depend on the signature only).
5. Compares the two extracted sets and reports only the symbols that
   were actually removed or whose signature changed.

Additive growth (new symbols, new fields, new enum variants) is
silent. A removed symbol, a renamed symbol, or a signature change
(type, parameter list, return type) is reported and exits non-zero.

Usage:

    scripts/abi_freeze_check.py <baseline-rev> [head-rev]

`head-rev` defaults to `HEAD` (the working tree). The script reads
the headers from the git tree at each rev (no checkout needed) via
`git show <rev>:<path>`.

Exit codes: 0 = no breaking change, 1 = breaking change found,
2 = usage / IO error.
"""

from __future__ import annotations

import re
import subprocess
import sys
from dataclasses import dataclass, field
from typing import Dict, List, Tuple

# The two headers the gate protects. `lr_ffi.h` is the C ABI surface
# generated by cbindgen; `librouting.hpp` is the header-only C++
# RAII wrapper built on top of it.
HEADERS: Tuple[str, ...] = ("include/lr_ffi.h", "include/librouting.hpp")

# A #define line. cbindgen does not emit multi-line #define
# directives, so we do not need to handle backslash continuations.
DEFINE_RE = re.compile(r"^#define\s+([A-Za-z_][A-Za-z0-9_]*)\s+(.*)$")

# A typedef line. `typedef <stuff> NAME;` — we capture the trailing
# NAME (the alias) and use the full normalised text as the signature.
# This catches `typedef int32_t lr_session_id_t;`, `typedef struct
# OpaqueFoo *lr_foo_t;` and `typedef struct Foo { ... } *handle_t;`
# (the latter after we join the multi-line struct).
TYPEDEF_RE = re.compile(r"^typedef\s+(.*)\b([A-Za-z_][A-Za-z0-9_]*)\s*;\s*$")

# A struct / enum / union / class block opener. We capture the kind
# and the tag name so `struct Foo` and `class Foo` do not collide.
# `class` is C++ only and is the only addition over the C struct /
# enum / union set. The `[^{]*` after the tag name accommodates a
# C++ base-class list (`class Foo : public Bar { ... }`) — the tag
# is still captured, and the body (including the base list) is the
# signature.
#
# C++11 scoped enums (`enum class NAME { ... }` and
# `enum struct NAME { ... }`) carry a `class` / `struct` keyword
# between `enum` and the tag name. Without handling that, the
# regex would capture `class` / `struct` as the tag name and every
# scoped enum in the C++ header would collide under the same key.
# The optional `(?:(?:class|struct)\s+)?` consumes that keyword
# before the tag name in the enum case.
AGGREGATE_OPEN_RE = re.compile(
    r"^(struct|enum|union|class)\s+"
    r"(?:(?<=enum\s)(?:class|struct)\s+)?"
    r"([A-Za-z_][A-Za-z0-9_]*)[^{]*\{"
)

# A function declaration. The regex is anchored so a typedef /
# struct / enum / union / class line cannot match. It captures the
# return type, the function name and the parameter list. C function
# declarations end with `;`; C++ inline definitions end with `{ ... }`
# (we strip the body before this regex runs so the form is the same).
FUNC_DECL_RE = re.compile(
    r"^(?!(?:typedef|struct|enum|union|class|#)\b)"
    r"(?P<ret>[A-Za-z_][A-Za-z0-9_\s\*]*?)\s*"
    r"(?P<name>[A-Za-z_][A-Za-z0-9_]*)\s*"
    r"\((?P<params>[^;]*)\)\s*;\s*$"
)

# A C++ inline function definition opener. The body is stripped
# before the FUNC_DECL_RE check, leaving `inline RET name(params) ;`
# — we capture `inline` here so we can strip it before normalising
# the signature (the `inline` storage-class specifier is not part
# of the ABI; what matters is the return type, name, parameters
# and const-ness).
INLINE_PREFIX_RE = re.compile(r"^inline\s+")
CONST_SUFFIX_RE = re.compile(r"\)\s*const\b")


@dataclass
class AbiSurface:
    """The ABI surface extracted from one header set.

    Each field is a `dict[name -> normalised_signature]`. Names are
    the C-side identifier; the signature is the full normalised
    declaration text (for functions and typedefs) or the full body
    (for struct / enum / union / class). Two surfaces are compared
    by name-set and by signature equality.
    """

    defines: Dict[str, str] = field(default_factory=dict)
    typedefs: Dict[str, str] = field(default_factory=dict)
    structs: Dict[str, str] = field(default_factory=dict)
    functions: Dict[str, str] = field(default_factory=dict)


def git_show(rev: str, path: str) -> str:
    """Read a file from a git rev without a checkout."""
    try:
        out = subprocess.run(
            ["git", "show", f"{rev}:{path}"],
            check=True,
            capture_output=True,
            text=True,
        )
    except subprocess.CalledProcessError as e:
        # `git show <rev>:<path>` on a rev where the path does not
        # exist yet exits non-zero; the caller treats this as
        # "header absent at baseline" rather than a hard error so
        # the gate can be a no-op for the very first release cut.
        if e.returncode == 128 and "exists on" in (e.stderr or ""):
            return ""
        raise
    return out.stdout


def strip_comments(text: str) -> str:
    """Remove C and C++ comments. cbindgen output uses both styles."""
    out = []
    i = 0
    n = len(text)
    while i < n:
        if text[i : i + 2] == "/*":
            end = text.find("*/", i + 2)
            if end == -1:
                # Unterminated comment — drop the rest. cbindgen never
                # emits one; this is defensive.
                break
            i = end + 2
            out.append(" ")
        elif text[i : i + 2] == "//":
            end = text.find("\n", i + 2)
            if end == -1:
                break
            i = end
            # Keep the newline so line structure is preserved.
            out.append("\n")
        else:
            out.append(text[i])
            i += 1
    return "".join(out)


def unwrap_namespaces(text: str) -> str:
    """Replace `namespace NAME { ... }` wrappers with their contents
    so the brace-depth tracker sees top-level constructs at depth 0.

    C++ header-only wrappers (librouting.hpp) put the public API
    inside one or more `namespace NAME { ... }` blocks. Without
    unwrapping, the brace-depth tracker in `join_logical_blocks`
    treats the namespace brace as the top-level block, so every
    class / struct / function inside the namespace is invisible to
    the symbol extractor (it is at depth >= 1 inside the namespace
    block). This walks the text and replaces each top-level
    `namespace NAME {` opener and its matching close brace with
    whitespace so the inner constructs are exposed at depth 0.

    Nested namespaces are handled correctly because we walk at
    depth 0 — once we strip the outer namespace, the inner one
    becomes a top-level block we strip in the next pass. We do a
    single pass for now because the librouting header only carries
    one top-level namespace; if a future header nests namespaces,
    we re-enter this function until the depth settles.
    """
    out: List[str] = []
    i = 0
    n = len(text)
    while i < n:
        # Look for `namespace <name> {` at depth 0. We do not look
        # inside strings / comments because `strip_comments` has
        # already run by the time we get here.
        if text[i:i+9] == "namespace" and (i == 0 or text[i-1] in " \t\n"):
            # Find the next `{` after `namespace NAME`.
            j = text.find("{", i)
            if j == -1:
                out.append(text[i:])
                break
            # Replace the opener with whitespace of the same line
            # length so line numbers stay aligned (helps debugging).
            opener = text[i:j+1]
            out.append(" " * len(opener))
            # Walk to the matching close brace at depth 0 (relative
            # to this opener).
            depth = 1
            k = j + 1
            while k < n and depth > 0:
                c = text[k]
                if c == "{":
                    depth += 1
                    out.append(c)
                elif c == "}":
                    depth -= 1
                    if depth == 0:
                        # Drop this closing brace — it closes the
                        # namespace, not anything inside. Replace
                        # with a newline so the next construct starts
                        # on its own line.
                        out.append("\n")
                    else:
                        out.append(c)
                else:
                    out.append(c)
                k += 1
            i = k
        else:
            out.append(text[i])
            i += 1
    return "".join(out)


def normalise(text: str) -> str:
    """Collapse whitespace runs and trim. Used for signature
    comparison so `int32_t  foo  (void)` matches `int32_t foo(void)`."""
    return re.sub(r"\s+", " ", text).strip()


def join_logical_blocks(text: str) -> List[str]:
    """Join continuation lines into brace-balanced logical blocks.

    We walk the comment-stripped text and accumulate blocks. A
    logical block ends when brace depth returns to 0 AND the line
    ends with `;` (a declaration) or `}` (a class / struct / enum
    body OR a C++ inline-function body).

    `#define` and `#include` lines are single-line blocks; we flush
    any pending block first so a stray `#define` between two halves
    of a wrapped signature (cbindgen never emits one) does not
    corrupt the join.

    The output is a list of normalised block strings ready for the
    regex extraction. Each block is either:
    - a preprocessor directive (starts with `#`)
    - a function declaration (`RET name(params);`)
    - a function definition (`inline RET name(params) { body }` —
      the body is stripped before extraction so the signature is
      what we compare)
    - a typedef (`typedef ... NAME;`)
    - a struct / enum / union / class block (`struct NAME { ... };`)
    """
    blocks: List[str] = []
    buf: List[str] = []
    depth = 0
    for raw in text.splitlines():
        line = raw.rstrip()
        if not line:
            continue
        # Preprocessor directives are single-line; flush any
        # pending block first.
        if line.startswith("#"):
            if buf and depth == 0:
                blocks.append(" ".join(buf))
                buf = []
            blocks.append(line)
            continue
        buf.append(line)
        # Track brace depth so a `;` inside a struct body does not
        # end the block prematurely.
        depth += line.count("{") - line.count("}")
        # A logical block ends when brace depth returns to 0 AND
        # the line ends with `;` (declaration) or `}` (body). This
        # distinguishes a function declaration's continuation line
        # (which does not have `;` or `}`) from the final line (which
        # does), so a multi-line declaration joins into a single
        # block.
        if depth == 0 and (line.endswith(";") or line.endswith("}")):
            blocks.append(" ".join(buf))
            buf = []
    if buf:
        blocks.append(" ".join(buf))
    return blocks


def strip_inline_body(block: str) -> str:
    """For a C++ inline function definition `inline RET name(params) { body }`,
    return the signature `inline RET name(params) ;` so the FUNC_DECL_RE
    matcher can pick it up. Returns the input unchanged for blocks
    that are not inline function definitions.

    The body is implementation detail — embedders depend on the
    signature (return type, name, parameters, const-ness) only.
    """
    # Find the first `{` at brace depth 0 — that opens the body.
    # If there is no `{`, the block is a declaration ending in `;`
    # (already in the right shape for FUNC_DECL_RE).
    depth = 0
    open_brace_idx = -1
    in_params = False
    i = 0
    n = len(block)
    while i < n:
        c = block[i]
        if c == "(":
            in_params = True
        elif c == ")":
            in_params = False
        elif c == "{":
            if depth == 0:
                open_brace_idx = i
                break
            depth += 1
        elif c == "}":
            depth -= 1
        i += 1
    if open_brace_idx == -1:
        return block
    # Find the matching close brace.
    depth = 1
    i = open_brace_idx + 1
    while i < n:
        c = block[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                break
        i += 1
    # `signature = block[:open_brace_idx] + ';'`
    signature = block[:open_brace_idx].rstrip()
    # Preserve a `const` qualifier that comes between `)` and `{` —
    # `void Foo::bar() const { ... }` — by walking back from the
    # brace to capture trailing `const`. We already sliced at the
    # brace so the `const` (if any) is in the signature slice.
    return f"{signature} ;"


def extract_surface(text: str) -> AbiSurface:
    """Extract the ABI surface from one header's text."""
    surf = AbiSurface()
    cleaned = strip_comments(text)
    # Strip C++ namespace wrappers so the brace-depth tracker in
    # `join_logical_blocks` sees top-level constructs at depth 0.
    # Without this, every class / struct / inline function inside
    # `namespace librouting { ... }` is invisible to the extractor
    # (it sits at depth >= 1 inside the namespace block).
    cleaned = unwrap_namespaces(cleaned)
    for block in join_logical_blocks(cleaned):
        block = normalise(block)
        if not block:
            continue
        m = DEFINE_RE.match(block)
        if m:
            name = m.group(1)
            value = normalise(m.group(2))
            surf.defines[name] = value
            continue
        # Struct / enum / union / class blocks. The opening carries
        # the tag; the closing ends with `};` (or just `}` for a
        # class definition). We re-extract the tag and the full body
        # after the join step produced a single logical block.
        m = AGGREGATE_OPEN_RE.match(block)
        if m:
            kind = m.group(1)
            tag = m.group(2)
            # The full normalised body is the signature. We key on
            # (kind, tag) so a `struct Foo` and `class Foo` do not
            # collide.
            surf.structs[f"{kind} {tag}"] = block
            continue
        # A typedef line may itself be `typedef struct Foo { ... }
        # *handle_t;` — the join step already collapsed it to one
        # block. We capture the alias name and the full text as the
        # signature.
        m = TYPEDEF_RE.match(block)
        if m:
            alias = m.group(2)
            surf.typedefs[alias] = block
            continue
        # A C++ inline function definition has a body — strip it
        # first so the signature is what we compare. The result is
        # `inline RET name(params) ;` (or `... ) const ;`), which
        # the FUNC_DECL_RE matcher handles after we drop the
        # `inline` prefix.
        candidate = strip_inline_body(block)
        # `inline` is a storage-class specifier, not part of the
        # ABI — drop it before signature comparison so a transition
        # from a header-only inline definition to a non-inline
        # declaration (or vice versa) does not register as a
        # signature change.
        candidate = INLINE_PREFIX_RE.sub("", candidate)
        # Preserve `const` member-function qualifier in the
        # canonical form: `name(params) const;` (with a space
        # before `const`). The strip step leaves
        # `name(params) const ;` with `const` already outside the
        # parens; the FUNC_DECL_RE captures the params as
        # `[^;]*` so the `const` lands in the captured return-type
        # tail. We re-normalise after to collapse any extra space.
        candidate = normalise(candidate)
        # Function declaration. The regex is anchored so a typedef
        # or aggregate block cannot match.
        m = FUNC_DECL_RE.match(candidate)
        if m:
            name = m.group("name")
            # Reconstruct the canonical signature:
            # `ret name(params);` — the `const` (if any) is in
            # `params` because the regex captures `[^;]*` for the
            # parameter list. That is fine for the comparator: two
            # surfaces with the same `ret name(params);` form
            # compare equal regardless of `const` placement.
            ret = normalise(m.group("ret"))
            params = normalise(m.group("params"))
            surf.functions[name] = f"{ret} {name}({params});"
            continue
        # Anything else (forward declarations like `struct Foo;`,
        # `extern "C" { ... }` blocks, namespace wrappers, etc.)
        # is not part of the ABI surface we track here.
    return surf


def collect(rev: str) -> AbiSurface:
    """Read both headers at `rev` and merge their surfaces."""
    surf = AbiSurface()
    for path in HEADERS:
        text = git_show(rev, path)
        if not text:
            continue
        per_file = extract_surface(text)
        for k, v in per_file.defines.items():
            surf.defines[k] = v
        for k, v in per_file.typedefs.items():
            surf.typedefs[k] = v
        for k, v in per_file.structs.items():
            surf.structs[k] = v
        for k, v in per_file.functions.items():
            surf.functions[k] = v
    return surf


def diff_surface(
    name: str,
    baseline: Dict[str, str],
    head: Dict[str, str],
) -> Tuple[List[str], List[Tuple[str, str, str]]]:
    """Return (removed, changed). `changed` is a list of
    (name, baseline_signature, head_signature) tuples."""
    removed = sorted(set(baseline) - set(head))
    changed: List[Tuple[str, str, str]] = []
    for k in sorted(set(baseline) & set(head)):
        if baseline[k] != head[k]:
            changed.append((k, baseline[k], head[k]))
    return removed, changed


def main(argv: List[str]) -> int:
    if len(argv) < 2 or len(argv) > 3:
        print(__doc__, file=sys.stderr)
        return 2
    baseline = argv[1]
    head = argv[2] if len(argv) > 2 else "HEAD"
    print(f"ABI freeze check: {baseline} -> {head}")
    base_surf = collect(baseline)
    head_surf = collect(head)
    if not base_surf.defines and not base_surf.typedefs \
            and not base_surf.structs and not base_surf.functions:
        print(
            f"no header content at baseline {baseline}; "
            "treating the gate as a no-op for the first release cut"
        )
        return 0
    total = 0
    for label, base, head in (
        ("#define macro", base_surf.defines, head_surf.defines),
        ("typedef", base_surf.typedefs, head_surf.typedefs),
        ("struct/enum/union/class", base_surf.structs, head_surf.structs),
        ("function", base_surf.functions, head_surf.functions),
    ):
        removed, changed = diff_surface(label, base, head)
        if removed:
            total += len(removed)
            print(f"\n--- removed {label}s ({len(removed)}) ---")
            for name in removed:
                print(f"  - {name}: {base[name]}")
        if changed:
            total += len(changed)
            print(f"\n--- changed {label}s ({len(changed)}) ---")
            for name, old, new in changed:
                print(f"  ~ {name}:")
                print(f"      baseline: {old}")
                print(f"      head:     {new}")
    if total:
        print(
            f"\n::error::Breaking C ABI change since {baseline} — "
            f"{total} symbol(s) removed or modified. Per "
            "docs/RELEASE-PLAN.md §1 Tier 2, a breaking ABI change "
            "is a major version bump."
        )
        return 1
    # Surface the additive deltas as a positive signal so the CI log
    # shows what grew. This is informational only.
    for label, base, head in (
        ("#define macro", base_surf.defines, head_surf.defines),
        ("typedef", base_surf.typedefs, head_surf.typedefs),
        ("struct/enum/union/class", base_surf.structs, head_surf.structs),
        ("function", base_surf.functions, head_surf.functions),
    ):
        added = sorted(set(head) - set(base))
        if added:
            print(
                f"additive: {len(added)} new {label}(s) since "
                f"{baseline} (allowed)"
            )
    print(
        f"OK: no symbol removed or modified since {baseline} "
        "(additions are allowed)."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
